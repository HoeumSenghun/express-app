export const translations = { en, km }

export function t(dict, key, vars) {
  const keys = key.split('.')
  let val = dict
  for (const k of keys) {
    val = val?.[k]
  }
  if (typeof val !== 'string') return key
  if (!vars) return val
  return val.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
}
